            <h6 class="fw-bold"><b>Overview</b></h6>
            <p class="text-justify">The Commonwealth Health Center (CHC) in Fananganan, Saipan, is the only hospital in the CNMI. CHCC describes it as &ldquo;an 86-bed, Medicare-certified hospital.&rdquo; Its services include emergency medicine, obstetrics, neonatal and adult intensive care, pediatrics, radiology and a newly established oncology unit. CHCC also runs the Community Guidance Center (behavioral health) and the Dr. Jose T. Villagomez Center for Dialysis.</p>
            <p class="text-justify"><strong>Note:</strong> The CNMI has no hospital classification law; the hospital&rsquo;s status rests on Public Law 16-51 and on its federal Medicare certification. Record it as &ldquo;Hospital &mdash; public (CHCC), Medicare-certified, general acute care.&rdquo; Check current Medicare certification status with CMS, because certification is a condition for federal reimbursement.</p>
            <h6 class="fw-bold"><b>Role</b></h6>
            <ul>
                <li>Serve as the only inpatient hospital and the referral point for the Tinian and Rota health centers</li>
                <li>Provide emergency, inpatient, intensive care, maternity, pediatric and specialist outpatient services</li>
                <li>Initiate off-island referrals through the Medical Referral Program.</li>
            </ul>
